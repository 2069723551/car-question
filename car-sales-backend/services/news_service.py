def get_news(limit: int = 6) -> list[dict]:
    """返回资讯列表（按日期倒序，默认最多 6 条，不含正文）"""
    items = sorted(NEWS_ITEMS, key=lambda x: x["date"], reverse=True)
    return [{k: v for k, v in x.items() if k != "content"} for x in items[:limit]]


def get_news_detail(news_id: int) -> dict | None:
    """按 id 返回单条资讯全文"""
    for item in NEWS_ITEMS:
        if item["id"] == news_id:
            return item
    return None
